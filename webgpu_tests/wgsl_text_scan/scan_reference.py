"""Compare the driver's WGSL text-scan facts for every engine variant against a stored reference.

Input on stdin: lines "<module>\t<mode>\t<fact>", where <mode> is "" or "--keep-rw" and <fact> is one line of
scan_dump's output (run_tests.sh produces them). scan_reference.txt beside this script holds the same facts for
every engine variant as derived from Tint's WGSL (the converter before SPIRV-Cross) when SPIRV-Cross replaced it
(webgpu_notes/TASKS.md §2.35): the driver builds bind group layouts from these facts, so SPIRV-Cross's output
must keep producing them. Format: "F <n> <fact>" defines fact n; "M <module>[ --keep-rw] <n,n,...>" lists a
module's facts.

Usage: python3 scan_reference.py <scan_reference.txt>            compare stdin with the reference
       python3 scan_reference.py --write <scan_reference.txt>    write stdin as the new reference
A reference module missing from stdin fails (a renamed or removed variant is a deliberate reference update);
a module the reference does not know is listed, not failed. Exit status 1 on any difference.
"""

import sys
from collections import defaultdict


def read_stdin():
    modules = defaultdict(set)
    for line in sys.stdin:
        line = line.rstrip("\n")
        if not line:
            continue
        name, mode, fact = line.split("\t", 2)
        modules[name + (" " + mode if mode else "")].add(fact)
    return modules


def write(path, modules):
    facts = sorted({f for fs in modules.values() for f in fs})
    index = {f: i for i, f in enumerate(facts)}
    with open(path, "w") as out:
        out.write("# Generated by webgpu_tests/wgsl_text_scan/scan_reference.py --write; see its docstring.\n")
        for i, f in enumerate(facts):
            out.write(f"F {i} {f}\n")
        for name in sorted(modules):
            out.write(f"M {name} {','.join(str(index[f]) for f in sorted(modules[name]))}\n")
    print(f"wrote {len(modules)} module scans, {len(facts)} distinct facts to {path}")


def read(path):
    facts = {}
    modules = {}
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("F "):
            _, i, fact = line.split(" ", 2)
            facts[int(i)] = fact
        elif line.startswith("M "):
            name, ids = line[2:].rsplit(" ", 1)
            modules[name] = {facts[int(i)] for i in ids.split(",") if i}
    return modules


if len(sys.argv) == 3 and sys.argv[1] == "--write":
    write(sys.argv[2], read_stdin())
    sys.exit(0)
if len(sys.argv) != 2:
    sys.exit(__doc__)

reference = read(sys.argv[1])
current = read_stdin()
missing = sorted(set(reference) - set(current))
unknown = sorted(set(current) - set(reference))
differ = [n for n in sorted(reference) if n in current and current[n] != reference[n]]
print(
    f"against the stored reference: {len(reference) - len(missing) - len(differ)}/{len(reference)} identical, "
    f"{len(differ)} differ, {len(missing)} missing, {len(unknown)} not in reference"
)
for n in differ[:5]:
    print(f"DIFF {n}")
    for f in sorted(reference[n] - current[n])[:4]:
        print(f"  - {f}")
    for f in sorted(current[n] - reference[n])[:4]:
        print(f"  + {f}")
for n in missing[:5]:
    print(f"  missing: {n}")
for n in unknown[:5]:
    print(f"  not in reference (no check): {n}")
sys.exit(1 if differ or missing else 0)
