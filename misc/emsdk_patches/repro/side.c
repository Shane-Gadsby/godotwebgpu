// A side module carrying an EM_ASM body. The EM_ASM is the whole point: it forces
// the side module to register into ASM_CONSTS at instantiation time, which is the
// operation that races with the main module's own ASM_CONSTS initializer.
#include <emscripten.h>

int side_value(void) {
	return EM_ASM_INT({ return 40 + 2; });
}
